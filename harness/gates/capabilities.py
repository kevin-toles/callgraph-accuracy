"""capabilities.py GOLDEN_REPORT.json — writes fanout/CAPABILITIES.md and fanout/KNOWN_GAPS.json
from the golden corpus (testdata/golden), its dispositions, and the previous KNOWN_GAPS.json.
A known gap whose golden case passes is closed (dropped); one whose case fails stays; one SPEC
does not decide stays, marked undecided. Open defects with a written note are added."""
import json, glob, os, sys, collections
G = os.environ.get('CALLGRAPH_GOLDEN', os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'golden'))
F = os.environ.get('CALLGRAPH_FANOUT', os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'results'))
rep = json.load(open(sys.argv[1]))
disp = json.load(open(os.path.join(G, 'dispositions.json')))
old = json.load(open(os.path.join(F, 'KNOWN_GAPS.json.bak-2026-11-10')))
UNSUPPORTED = {  # deliberate scope limits, each reported in call_graph.coverage where detectable
 '*': ['directories named vendor/, node_modules/, build output and fetched dependencies are skipped (coverage: skipped)'],
 'go': ['_test.go files are not analyzed', 'packages that fail to type-check are not graphed (coverage: go_package_load_error)'],
 'ocaml': ['vendor/ is skipped'],
 'elixir': ['HEEx templates are not analyzed'],
 'kotlin': ['files the grammar cannot parse are partial (coverage: syntax_error)'],
}
langs = sorted({p.split('/')[-3] for p in glob.glob(G + '/*/*/expected.json')} | set(old))
cases = collections.defaultdict(list)
for p in sorted(glob.glob(G + '/*/*/expected.json')):
    k = p[len(G) + 1:].rsplit('/', 1)[0]; d = json.load(open(p))
    cases[k.split('/')[0]].append((k, d, rep.get(k, {}).get('status', 'missing')))
gaps = {}
md = ['# Call-graph capability matrix', '',
      'Generated by `gates/capabilities.py` from the golden corpus (`struct-analyzer-service/testdata/golden`, written from SPEC.md by authors blind to the implementation), its recorded dispositions, and the scope limits below. Reviewers use it per SPEC Method step 5: **unsupported** constructs are recall gaps, not wrong edges; **open defects** are wrong when the output shows them.', '',
      '| Language | Golden cases | Pass | Open defects | Accepted limitations | Undecided (spec gap) |', '|---|---|---|---|---|---|']
rows, detail = [], []
for l in langs:
    cs = cases.get(l, [])
    st = collections.Counter(s for _, _, s in cs)
    od = [k for k, _, s in cs if s == 'fail' and disp.get(k, {}).get('disposition') == 'open defect']
    al = [k for k, _, s in cs if s == 'fail' and disp.get(k, {}).get('disposition') == 'accepted limitation']
    sg = [(k, d['spec_gap']) for k, d, s in cs if s == 'spec_gap']
    rows.append(f'| {l} | {len(cs)} | {st["pass"]} | {len(od)} | {len(al)} | {len(sg)} |')
    detail += ['', f'## {l}', '']
    detail.append('**Unsupported (by design):** ' + '; '.join(UNSUPPORTED.get('*', []) + UNSUPPORTED.get(l, [])) + '.')
    if od:
        detail += ['', '**Open defects** (golden case fails; wrong output when it occurs):']
        detail += [f'- `{k}`: {disp[k]["note"]}' for k in od]
    if al:
        detail += ['', '**Accepted limitations:**'] + [f'- `{k}`: {disp[k]["note"]}' for k in al]
    if sg:
        detail += ['', '**Undecided by SPEC** (no expectation; see GOLDEN_AUTHOR_QUESTIONS.md):'] + [f'- `{k}`: {q}' for k, q in sg]
    closed = [d['source'][len('KNOWN_GAP: '):] for k, d, s in cs if d.get('source', '').startswith('KNOWN_GAP') and s == 'pass']
    if closed:
        detail += ['', '**Known gaps closed** (their golden case passes):'] + [f'- {c}' for c in closed]
    # KNOWN_GAPS.json
    keep = []
    for g in old.get(l, {}).get('gaps', []):
        st_g = [s for k, d, s in cs if g[:40] in d.get('source', '')]
        if not st_g or 'fail' in st_g:
            keep.append(g)
        elif 'spec_gap' in st_g and 'pass' not in st_g:
            keep.append(g + ' (behaviour not yet decided in SPEC)')
    gapcase = {k for k, d, s in cs if d.get('source', '').startswith('KNOWN_GAP')}
    for k in od:
        n = disp[k]['note']
        if k not in gapcase and not n.startswith('expected ') and n not in keep:
            keep.append(n)
    entry = {'gaps': keep}
    if old.get(l, {}).get('note'):
        entry['note'] = old[l]['note']
    gaps[l] = entry
open(os.path.join(F, 'CAPABILITIES.md'), 'w').write('\n'.join(md + rows + detail) + '\n')
json.dump(gaps, open(os.path.join(F, 'KNOWN_GAPS.json'), 'w'), indent=1)
print('\n'.join(rows))
